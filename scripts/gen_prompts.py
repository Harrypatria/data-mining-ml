#!/usr/bin/env python3
"""Generate every platform prompt from adapters/core-prompt.md plus overlays, and sync packaged prompt copies.

Usage:
    python gen_prompts.py            write dist/*.md and templates/src/mlkit/prompts/*
    python gen_prompts.py --check    exit 1 if any generated file is stale
    python gen_prompts.py --print TARGET   print one rendered prompt (see TARGETS)
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ADAPTERS = ROOT / "adapters"
GENERATED = "<!-- Generated by scripts/gen_prompts.py from adapters/. Edit the adapters, then regenerate. -->\n\n"

BOOTSTRAP = '''```python
# First cell: environment, seed and the project package (pinned)
import os, sys, subprocess
IN_COLAB = "google.colab" in sys.modules
SEED = 42
if IN_COLAB:
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "imbalanced-learn==0.14.2",
                    "git+https://github.com/Harrypatria/data-mining-ml@v1.0.0#subdirectory=templates"], check=True)
    from google.colab import userdata  # keys: userdata.get("OPENAI_API_KEY"); never paste keys into cells
from mlkit.persistence import library_versions
print(library_versions())
```'''

GEMINI_HEADER = """# Instructions for Gemini in Google Colab

Paste this into the Gemini side panel (or keep it as the first Markdown cell) before asking for analysis cells.
Follow every rule below when you write or fix cells in this notebook.

## Start every notebook with this bootstrap cell

""" + BOOTSTRAP + "\n\n"

AI_STUDIO_HEADER = """# System instructions for Google AI Studio

Use as the system instruction for a data science assistant. When the user shares data or results, apply these rules;
when no code can run, say which numbers must be computed instead of estimating them.

"""

NOTEBOOK_HEADER = """# Analysis rules (keep this as the first Markdown cell)

"""


def read(name: str) -> str:
    return (ADAPTERS / name).read_text(encoding="utf-8").strip() + "\n"


def core() -> str:
    return read("core-prompt.md")


def render(target: str) -> str:
    overlays = {"colab": "overlays/colab.md", "jupyterlab": "overlays/jupyterlab.md", "notebook": "overlays/notebook.md",
                "vscode": "overlays/vscode.md"}
    if target == "system":
        return GENERATED + core()
    if target == "gemini-colab":
        return GENERATED + GEMINI_HEADER + core() + "\n" + read(overlays["colab"])
    if target == "ai-studio":
        return GENERATED + AI_STUDIO_HEADER + core()
    if target == "notebook-cell":
        return GENERATED + NOTEBOOK_HEADER + core() + "\n" + read(overlays["notebook"])
    if target in overlays:
        return GENERATED + core() + "\n" + read(overlays[target])
    if target in ("agents", "claude-project", "replit"):
        return GENERATED + core() + "\n" + read(overlays["vscode"])
    if target == "cursor":
        return ("---\ndescription: Data mining and machine learning rules (CRISP-DM, leakage-safe pipelines, imbalance-aware metrics)\n"
                "globs: [\"**/*.py\", \"**/*.ipynb\", \"**/*.R\", \"**/*.sql\"]\nalwaysApply: false\n---\n\n") + GENERATED + core()
    raise SystemExit(f"unknown target {target}; choose from {', '.join(TARGETS)}")


TARGETS = ("system", "gemini-colab", "ai-studio", "notebook-cell", "colab", "jupyterlab", "notebook", "vscode",
           "agents", "cursor", "claude-project", "replit")
DIST = {"system-prompt.md": "system", "gemini-colab.md": "gemini-colab", "ai-studio.md": "ai-studio",
        "notebook-cell.md": "notebook-cell"}


def outputs() -> dict[Path, str]:
    files = {ROOT / "dist" / name: render(target) for name, target in DIST.items()}
    src, dst = ROOT / "templates" / "prompts", ROOT / "templates" / "src" / "mlkit" / "prompts"
    for f in sorted(src.iterdir()):
        if f.is_file():
            files[dst / f.name] = f.read_text(encoding="utf-8")
    return files


def main(argv: list[str]) -> int:
    if argv[:1] == ["--print"] and len(argv) == 2:
        sys.stdout.write(render(argv[1]))
        return 0
    check = "--check" in argv
    stale = []
    for path, text in outputs().items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != text:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    for p in stale:
        print(f"{'stale' if check else 'wrote'} {p.relative_to(ROOT).as_posix()}")
    if check and stale:
        print("run: python scripts/gen_prompts.py")
        return 1
    print(f"prompts {'in sync' if not stale else 'updated'}: core about {len(core()) // 4} tokens")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
